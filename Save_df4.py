    "def export_dividends(ticker):\n",
    "    today = pd.Timestamp.now(tz=pytz.timezone('America/New_York')).normalize()\n",
    "    series = yf.Ticker(ticker).dividends\n",
    "    if not series.empty:\n",
    "        dfdi = series.sort_index(ascending=False).to_frame(name='Dividend').reset_index()\n",
    "        dfdi.rename(columns={'index':'Date'}, inplace=True)\n",
    "        dfdi['Date'] = pd.to_datetime(dfdi['Date']).dt.tz_localize(None)\n",
    "        data = dfdi[['Date','Dividend']]\n",
    "    else:\n",
    "        first_date = BMonthEnd().rollback(today)\n",
    "        dates = []\n",
    "        for i in range(20):\n",
    "            candidate = first_date - pd.DateOffset(months=3*i)\n",
    "            candidate_bme = BMonthEnd().rollback(candidate)\n",
    "            dates.append(candidate_bme.normalize())\n",
    "        data = pd.DataFrame({'Date':dates,'Dividend':1})\n",
    "    data['Date'] = pd.to_datetime(data['Date']).dt.strftime('%Y-%m-%d')\n",
    "    data.sort_values('Date', ascending=False, inplace=True)\n",
    "    data.reset_index(drop=True, inplace=True)\n",
    "    data.to_excel(os.path.join(DIVIDEND_PATH, f'Div_{ticker}.xlsx'), index=False)\n",
    "\n",
    "if __name__ == '__main__':\n",
