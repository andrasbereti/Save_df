    "def clean_dynamic_df(df):\n",
    "    df.columns = [str(c).split('.')[0] for c in df.columns]\n",
    "    df = df.groupby(df.columns, axis=1).first()\n",
    "    df.reset_index(inplace=True)\n",
    "    df.rename(columns={'index':'Line Item'}, inplace=True)\n",
