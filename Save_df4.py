    "    return []\n",
    "\n",
    "def create_dataframe(reports, statement_name):\n",
    "    df = pd.DataFrame()\n",
    "    for r in reports:\n",
    "        date = pd.to_datetime(r.get('fiscalDateEnding')).strftime('%Y-%m-%d')\n",
    "        dfq = pd.DataFrame.from_dict(r, orient='index')\n",
    "        dfq.columns = [date]\n",
    "        dfq.index.name = statement_name\n",
    "        df = pd.concat([df, dfq], axis=1)\n",
